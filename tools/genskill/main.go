var funcs = template.FuncMap{
	"cell":    cell,
	"summary": summary,
	"status":  status,
	"yes":     func(b bool) string { return map[bool]string{true: "yes", false: ""}[b] },
	"limits":  limits,
	"code":    func(s string) string { return "`" + s + "`" },
	"join":    strings.Join,
	"inc":     func(i int) int { return i + 1 },
}

// cell makes text safe for one markdown table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "\r\n", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.TrimSpace(s)
}

// summary returns the first sentence of s, for pointer lists.
func summary(s string) string {
	s = cell(s)
	from := 0
	for {
		i := strings.Index(s[from:], ". ")
		if i < 0 {
			return s
		}
		end := from + i + 1
		head := strings.ToLower(s[:end])
		abbrev := false
		for _, a := range []string{"e.g.", "i.e.", "etc.", "vs.", "approx."} {
			if strings.HasSuffix(head, a) {
				abbrev = true
				break
			}
		}
		if !abbrev {
			return s[:end]
		}
		from = end
	}
}

func status(a attrInfo) string {
	var s string
	switch {
	case a.Required:
		s = "required"
	case a.Optional && a.Computed:
		s = "optional, computed"
	case a.Optional:
		s = "optional"
	case a.Computed:
		s = "computed"
	}
	if a.WriteOnly {
		s += ", write-only"
	}
	return s
}

func limits(b blockInfo) string {
	var p []string
	if b.MinItems > 0 {
		p = append(p, fmt.Sprintf("min %d", b.MinItems))
	}
	if b.MaxItems > 0 {
		p = append(p, fmt.Sprintf("max %d", b.MaxItems))
	}
	if len(p) == 0 {
		return ""
	}
	return " (" + strings.Join(p, ", ") + ")"
}

func parseTemplates() (*template.Template, error) {
	return template.New("genskill").Funcs(funcs).ParseFS(templateFS, "templates/*.tmpl")
}

// readExample returns the file content with LF endings, or "" if absent.
func readExample(path string) string {
	b, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	return strings.TrimRight(strings.ReplaceAll(string(b), "\r\n", "\n"), "\n")
}

// collection is every documented type of one provider build, each kind
// sorted by name.
type collection struct {
	Resources   []typeDoc
	DataSources []typeDoc
	Actions     []typeDoc
	Ephemeral   []typeDoc
	Lists       []typeDoc
	Functions   []typeDoc
	Provider    typeDoc
}

// all returns every type except the provider, kind by kind.
func (c collection) all() []typeDoc {
	var out []typeDoc
	for _, s := range [][]typeDoc{c.Resources, c.DataSources, c.Actions, c.Ephemeral, c.Lists, c.Functions} {
		out = append(out, s...)
	}
	return out
}

func sortDocs(d []typeDoc) {
	sort.Slice(d, func(i, j int) bool { return d[i].Name < d[j].Name })
}

// schemaDocs walks every schema of one kind, attaching the example file
// examples/<dir>/<type>/<file> when examplesDir is set.
func schemaDocs(schemas map[string]*tfprotov6.Schema, kind, examplesDir, dir, file string) []typeDoc {
	var out []typeDoc
	for name, s := range schemas {
		td := walkSchema(name, kind, s)
		if examplesDir != "" {
			td.Example = readExample(filepath.Join(examplesDir, dir, name, file))
		}
		out = append(out, td)
	}
	sortDocs(out)
	return out
}

// collect turns the protocol response into sorted type docs. repl (may be
// nil) adds framework-derived RequiresReplace flags to resources.
func collect(resp *tfprotov6.GetProviderSchemaResponse, examplesDir string, repl replaceSet) collection {
	var c collection
	c.Resources = schemaDocs(resp.ResourceSchemas, kindResource, examplesDir, "resources", "resource.tf")
	for i := range c.Resources {
		td := &c.Resources[i]
		markReplacements(&td.Root, td.Name, repl)
		if examplesDir != "" {
			td.Import = readExample(filepath.Join(examplesDir, "resources", td.Name, "import.sh"))
		}
	}
	c.DataSources = schemaDocs(resp.DataSourceSchemas, kindDataSource, examplesDir, "data-sources", "data-source.tf")
	actions := make(map[string]*tfprotov6.Schema, len(resp.ActionSchemas))
	for name, a := range resp.ActionSchemas {
		if a != nil {
			actions[name] = a.Schema
		}
	}
	c.Actions = schemaDocs(actions, kindAction, examplesDir, "actions", "action.tf")
	c.Ephemeral = schemaDocs(resp.EphemeralResourceSchemas, kindEphemeral, examplesDir, "ephemeral-resources", "ephemeral-resource.tf")
	c.Lists = schemaDocs(resp.ListResourceSchemas, kindList, examplesDir, "list-resources", "list-resource.tfquery.hcl")
	for name, f := range resp.Functions {
		td := walkFunction(name, f)
		if examplesDir != "" {
			td.Example = readExample(filepath.Join(examplesDir, "functions", name, "function.tf"))
		}
		c.Functions = append(c.Functions, td)
	}
	sortDocs(c.Functions)
	c.Provider = walkSchema("docker", kindProvider, resp.Provider)
	if examplesDir != "" {
		c.Provider.Example = readExample(filepath.Join(examplesDir, "provider", "provider.tf"))
	}
	return c
}

// renderOpts controls render.
type renderOpts struct {
	Examples       string     // examples directory; "" skips examples
	Replace        replaceSet // framework RequiresReplace flags; nil uses description text only
	ReadmeSkillDir string     // link prefix from README_resources.md to the skill dir; "" skips the README
	ReadmeDocsDir  string     // link prefix from README_resources.md to docs/
}

// exampleGaps reports every type or path in uses (keyed by HCL address) that
// the build does not have.
func exampleGaps(uses map[string][]string, byAddr map[string]typeDoc) []string {
	addrs := make([]string, 0, len(uses))
	for a := range uses {
		addrs = append(addrs, a)
	}
	sort.Strings(addrs)
	var gaps []string
	for _, a := range addrs {
		td, ok := byAddr[a]
		if !ok {
			kind, name := "resource", a
			if k, n, found := strings.Cut(a, "."); found {
				kind, name = k, n
			}
			gaps = append(gaps, fmt.Sprintf("%s `%s` is not registered in this build", kind, name))
			continue
		}
		for _, p := range uses[a] {
			if !hasPath(td.Root, p) {
				gaps = append(gaps, fmt.Sprintf("`%s.%s` is not in the schema", a, p))
			}
		}
	}
	return gaps
}

// render produces every skill file keyed by slash path relative to the skill
// directory, the README_resources.md content (nil when disabled), and
// warnings about example drift.
func render(resp *tfprotov6.GetProviderSchemaResponse, ro renderOpts) (map[string][]byte, []byte, []string, error) {
	tmpl, err := parseTemplates()
	if err != nil {
		return nil, nil, nil, err
	}
	c := collect(resp, ro.Examples, ro.Replace)

	sd := skillData{
		Marker: generatedMarker, Provider: c.Provider,
		Actions: c.Actions, Ephemeral: c.Ephemeral, Lists: c.Lists, Functions: c.Functions,
		Resources: len(c.Resources), DataSources: len(c.DataSources),
	}
	pick := func(docs []typeDoc, key string) []typeDoc {
		var out []typeDoc
		for _, d := range docs {
			if layerOf(d.Name) == key {
				out = append(out, d)
			}
		}
		return out
	}
	for _, l := range layerDefs {
		lv := layerView{
			Title: l.Title, Blurb: l.Blurb,
			Resources: pick(c.Resources, l.Key), DataSources: pick(c.DataSources, l.Key),
			Actions: pick(c.Actions, l.Key), Ephemeral: pick(c.Ephemeral, l.Key),
			Lists: pick(c.Lists, l.Key), Functions: pick(c.Functions, l.Key),
		}
		if l.Key == "other" && len(lv.All()) == 0 {
			continue
		}
		sd.Layers = append(sd.Layers, lv)
	}
	byAddr := map[string]typeDoc{}
	for _, td := range c.all() {
		byAddr[td.Address()] = td
	}
	for _, r := range c.Resources {
		for _, a := range replacementAttrs(r.Root) {
			sd.Replacements = append(sd.Replacements, replRow{Address: r.Name, Path: a.Path, Description: a.Description, Block: a.Block})
		}
		for _, a := range writeOnlyAttrs(r.Root) {
			sd.WriteOnly = append(sd.WriteOnly, replRow{Address: r.Name, Path: a.Path, Description: a.Description})
		}
	}
	sd.References = append([]typeDoc{c.Provider}, c.all()...)

	sd.ExampleGaps = exampleGaps(exampleUses, byAddr)
	sd.Example2Gaps = exampleGaps(example2Uses, byAddr)
	var warnings []string
	for _, g := range sd.ExampleGaps {
		warnings = append(warnings, "worked example: "+strings.ReplaceAll(g, "`", ""))
	}
	for _, g := range sd.Example2Gaps {
		warnings = append(warnings, "worked example 2: "+strings.ReplaceAll(g, "`", ""))
	}

	files := map[string][]byte{}
	var buf bytes.Buffer
	if err := tmpl.ExecuteTemplate(&buf, "skill.md.tmpl", sd); err != nil {
		return nil, nil, nil, fmt.Errorf("rendering SKILL.md: %w", err)
	}
	files["SKILL.md"] = normalize(buf.Bytes())
	for _, td := range sd.References {
		buf.Reset()
		if err := tmpl.ExecuteTemplate(&buf, "reference.md.tmpl", refData{Marker: generatedMarker, Doc: td, Blocks: subBlocks(td.Root)}); err != nil {
			return nil, nil, nil, fmt.Errorf("rendering %s: %w", td.File(), err)
		}
		files[td.File()] = normalize(buf.Bytes())
	}
	var readme []byte
	if ro.ReadmeSkillDir != "" {
		buf.Reset()
		rd := readmeData{
			Marker: generatedMarker, Layers: sd.Layers, Provider: c.Provider,
			SkillDir: ro.ReadmeSkillDir, DocsDir: ro.ReadmeDocsDir,
			Resources: len(c.Resources), DataSources: len(c.DataSources),
			Actions: len(c.Actions), Ephemeral: len(c.Ephemeral), Lists: len(c.Lists), Functions: len(c.Functions),
		}
		if rd.DocsDir == "" {
			rd.DocsDir = "docs"
		}
		if err := tmpl.ExecuteTemplate(&buf, "readme.md.tmpl", rd); err != nil {
			return nil, nil, nil, fmt.Errorf("rendering README_resources.md: %w", err)
		}
		readme = normalize(buf.Bytes())
	}
	return files, readme, warnings, nil
}

// normalize forces LF endings, strips trailing spaces, collapses runs of
// blank lines and ends the file with exactly one newline.
func normalize(b []byte) []byte {
	s := strings.ReplaceAll(string(b), "\r\n", "\n")
	lines := strings.Split(s, "\n")
	out := make([]string, 0, len(lines))
	inFence := false
	blank := 0
	for _, l := range lines {
		if strings.HasPrefix(strings.TrimSpace(l), "```") {
			inFence = !inFence
		}
		l = strings.TrimRight(l, " \t")
		if l == "" && !inFence {
			blank++
			if blank > 1 {
				continue
			}
		} else {
			blank = 0
		}
		out = append(out, l)
	}
	return []byte(strings.TrimSpace(strings.Join(out, "\n")) + "\n")
}

func sortedKeys(m map[string][]byte) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// staleFiles lists generated reference files on disk that render no longer
// produces.
func staleFiles(outDir string, files map[string][]byte) ([]string, error) {
	entries, err := os.ReadDir(filepath.Join(outDir, "reference"))
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var stale []string
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") {
			continue
		}
		rel := "reference/" + e.Name()
		if _, ok := files[rel]; ok {
			continue
		}
		b, err := os.ReadFile(filepath.Join(outDir, "reference", e.Name()))
		if err != nil {
			return nil, err
		}
		if bytes.Contains(b, []byte(generatedMarker)) {
			stale = append(stale, rel)
		}
	}
	sort.Strings(stale)
	return stale, nil
}

func writeFiles(outDir string, files map[string][]byte) ([]string, error) {
	for _, rel := range sortedKeys(files) {
		p := filepath.Join(outDir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(p, files[rel], 0o644); err != nil {
			return nil, err
		}
	}
	stale, err := staleFiles(outDir, files)
	if err != nil {
		return nil, err
	}
	for _, rel := range stale {
		if err := os.Remove(filepath.Join(outDir, filepath.FromSlash(rel))); err != nil {
			return nil, err
		}
	}
	return stale, nil
}

// checkFile compares one rendered file with disk and returns a drift message,
// or "" when it matches. CRLF on disk is not drift.
func checkFile(path string, want []byte) (string, error) {
	b, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return filepath.ToSlash(path) + " is missing", nil
	}
	if err != nil {
		return "", err
	}
	if !bytes.Equal(bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n")), want) {
		return filepath.ToSlash(path) + " differs", nil
	}
	return "", nil
}

// checkFiles compares rendered files with disk. CRLF on disk (a Windows
// checkout with autocrlf) is not drift.
func checkFiles(outDir string, files map[string][]byte) ([]string, error) {
	var diffs []string
	for _, rel := range sortedKeys(files) {
		b, err := os.ReadFile(filepath.Join(outDir, filepath.FromSlash(rel)))
		if errors.Is(err, os.ErrNotExist) {
			diffs = append(diffs, rel+" is missing")
			continue
		}
		if err != nil {
			return nil, err
		}
		if !bytes.Equal(bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n")), files[rel]) {
			diffs = append(diffs, rel+" differs")
		}
	}
	stale, err := staleFiles(outDir, files)
	if err != nil {
		return nil, err
	}
	for _, s := range stale {
		diffs = append(diffs, s+" is stale")
	}
	return diffs, nil
}
