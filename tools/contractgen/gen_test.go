func TestParseFilters(t *testing.T) {
	inv, err := Parse([]byte(sampleInventory))
	if err != nil {
		t.Fatal(err)
	}
	var ids []string
	for _, it := range inv.Items {
		ids = append(ids, it.ID)
	}
	if strings.Join(ids, ",") != "engine:act,engine:eph,engine:thing" {
		t.Errorf("kept %v", ids)
	}
	if _, err := Parse([]byte(`{"items":[{"id":"a","kind":"resource","outputs":[{}]},{"id":"a","kind":"resource","outputs":[{}]}]}`)); err == nil {
		t.Error("duplicate id must fail")
	}
	if _, err := Parse([]byte(`{`)); err == nil {
		t.Error("bad JSON must fail")
	}
}

func TestGenerate(t *testing.T) {
	inv, _ := Parse([]byte(sampleInventory))
	src, err := Generate(inv)
	if err != nil {
		t.Fatal(err)
	}
	s := string(src)
	for _, want := range []string{
		"// Code generated by tools/contractgen. DO NOT EDIT.",
		`MinAPI: "1.55"`,
		`contractComposeSpecVersion = "main@3a4a699"`,
		`contractComposeGoVersion = "v2.16.2"`,
		`contractDockerfileDefaultSyntax = "docker/dockerfile:1.28.0"`,
		"type contractEngineThing struct",
		"InspectJSON types.String `tfsdk:\"inspect_json\"`",
		"Inspect types.Object `tfsdk:\"inspect\"`",
		"Loose types.Dynamic `tfsdk:\"loose\"`",
		"Fidelity types.String `tfsdk:\"fidelity\"`",
		"ContentSHA256 types.String `tfsdk:\"content_sha256\"`",
		"type contractEngineEph struct",
		`Sensitive: true`,
		`FieldsComplete: false`,
		`Description: "Raw \"quoted\"."`,
		`{Name: "tail", TFType: "number", Default: "1000"`,
		`{Name: "since", TFType: "string", Default: ""`,
		`"engine:thing": func() contractModel { return &contractEngineThing{} }`,
	} {
		flat, w := strings.Join(strings.Fields(s), " "), strings.Join(strings.Fields(want), " ")
		if !strings.Contains(flat, w) {
			t.Errorf("generated code lacks %q", want)
		}
	}
	// Identity outputs and actions get no struct fields / types.
	if strings.Contains(s, "type contractEngineAct struct") || strings.Contains(s, "ID types.String `tfsdk:\"id\"`") {
		t.Error("action struct or identity field generated")
	}
	// Deterministic.
	src2, _ := Generate(inv)
	if !bytes.Equal(src, src2) {
		t.Error("output not deterministic")
	}
}

func TestHelpers(t *testing.T) {
	cases := map[string]string{"inspect_json": "InspectJSON", "content_sha256": "ContentSHA256", "engine_api_version": "EngineAPIVersion", "log_entries": "LogEntries"}
	for in, want := range cases {
		if got := GoFieldName(in); got != want {
			t.Errorf("GoFieldName(%q) = %q", in, got)
		}
	}
	if StructName("cli-only:manifest-inspect") != "contractCliOnlyManifestInspect" || StructName("dockerfile:ADD") != "contractDockerfileADD" {
		t.Error("StructName")
	}
	pins := map[string]string{"v2.16.2 @ abc": "v2.16.2", "dockerfile/1.28.0 @ f": "1.28.0", "main @ 3a4a6995e4": "main@3a4a699", "main": "main"}
	for in, want := range pins {
		if got := PinVersion(in); got != want {
			t.Errorf("PinVersion(%q) = %q", in, got)
		}
	}
	if GoFieldType(Output{TFType: "map(list(object({...})))"}) != "types.Map" || GoFieldType(Output{TFType: "object({a=string})"}) != "types.Object" || GoFieldType(Output{TFType: "tuple"}) != "" {
		t.Error("GoFieldType")
	}
}

func TestRunWriteAndCheck(t *testing.T) {
	dir := t.TempDir()
	inv := filepath.Join(dir, "inventory.json")
	out := filepath.Join(dir, "contract_gen.go")
	if err := os.WriteFile(inv, []byte(sampleInventory), 0o644); err != nil {
		t.Fatal(err)
	}
	var so, se bytes.Buffer
	if c := run([]string{"-inventory", inv, "-out", out, "-check"}, &so, &se); c != 1 {
		t.Errorf("check of a missing file: exit %d", c)
	}
	if c := run([]string{"-inventory", inv, "-out", out}, &so, &se); c != 0 {
		t.Fatalf("write: exit %d %s", c, se.String())
	}
	if c := run([]string{"-inventory", inv, "-out", out, "-check"}, &so, &se); c != 0 {
		t.Errorf("check after write: exit %d %s", c, se.String())
	}
	// CRLF checkouts are not drift.
	b, _ := os.ReadFile(out)
	_ = os.WriteFile(out, bytes.ReplaceAll(b, []byte("\n"), []byte("\r\n")), 0o644)
	if c := run([]string{"-inventory", inv, "-out", out, "-check"}, &so, &se); c != 0 {
		t.Errorf("CRLF: exit %d", c)
	}
	_ = os.WriteFile(out, append(b, "// edited\n"...), 0o644)
	if c := run([]string{"-inventory", inv, "-out", out, "-check"}, &so, &se); c != 1 {
		t.Errorf("drift: exit %d", c)
	}
	if c := run([]string{"-inventory", filepath.Join(dir, "nope.json")}, &so, &se); c != 2 {
		t.Errorf("missing inventory: exit %d", c)
	}
}

// TestCheckedInFileIsCurrent is `go run ./tools/contractgen -check` on the
// repository itself.
func TestCheckedInFileIsCurrent(t *testing.T) {
	root := filepath.Join("..", "..")
	var so, se bytes.Buffer
	c := run([]string{"-inventory", filepath.Join(root, "reference", "inventory.json"),
		"-out", filepath.Join(root, "internal", "provider", "contract_gen.go"), "-check"}, &so, &se)
	if c != 0 {
		t.Fatalf("contract_gen.go is stale (exit %d): %s", c, se.String())
	}
}
