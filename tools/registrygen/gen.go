package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

// Item is the part of a reference/inventory.json item registrygen reads.
type Item struct {
	ID      string `json:"id"`
	Layer   string `json:"layer"`
	Kind    string `json:"kind"`
	Name    string `json:"name"`
	Summary string `json:"summary"`
}

// Inventory is the part of reference/inventory.json registrygen reads.
type Inventory struct {
	Items []Item `json:"items"`
}

// Type is one registered Terraform type: a (kind, name) pair with every
// inventory item that names it.
type Type struct {
	Kind  string
	Name  string
	Items []Item
}

// kindInfo is how one inventory kind is registered.
type kindInfo struct {
	suffix  string // constructor name suffix
	iface   string // constructor return type
	genFunc string // generated function name
	pkg     string // import path of iface's package
}

// Kinds in registration order. dockerfile_block and skip are not registered.
var kindOrder = []string{"resource", "data_source", "action", "ephemeral_resource", "list_resource", "function"}

var kinds = map[string]kindInfo{
	"resource":           {"Resource", "resource.Resource", "genResources", "github.com/hashicorp/terraform-plugin-framework/resource"},
	"data_source":        {"DataSource", "datasource.DataSource", "genDataSources", "github.com/hashicorp/terraform-plugin-framework/datasource"},
	"action":             {"Action", "action.Action", "genActions", "github.com/hashicorp/terraform-plugin-framework/action"},
	"ephemeral_resource": {"EphemeralResource", "ephemeral.EphemeralResource", "genEphemeralResources", "github.com/hashicorp/terraform-plugin-framework/ephemeral"},
	"list_resource":      {"ListResource", "list.ListResource", "genListResources", "github.com/hashicorp/terraform-plugin-framework/list"},
	"function":           {"Function", "function.Function", "genFunctions", "github.com/hashicorp/terraform-plugin-framework/function"},
}

// LoadInventory reads reference/inventory.json.
func LoadInventory(path string) (*Inventory, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var inv Inventory
	if err := json.Unmarshal(b, &inv); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return &inv, nil
}

// Types returns the registered types of inv, grouped by (kind, name) and
// sorted by kind order, then name. Items in each type are sorted by id.
func Types(inv *Inventory) ([]Type, error) {
	idx := map[[2]string]*Type{}
	for _, it := range inv.Items {
		if _, ok := kinds[it.Kind]; !ok {
			continue // skip, dockerfile_block
		}
		if it.Name == "" {
			return nil, fmt.Errorf("item %s (%s) has no name", it.ID, it.Kind)
		}
		k := [2]string{it.Kind, it.Name}
		if idx[k] == nil {
			idx[k] = &Type{Kind: it.Kind, Name: it.Name}
		}
		idx[k].Items = append(idx[k].Items, it)
	}
	var out []Type
	for _, t := range idx {
		sort.Slice(t.Items, func(i, j int) bool { return t.Items[i].ID < t.Items[j].ID })
		out = append(out, *t)
	}
	rank := map[string]int{}
	for i, k := range kindOrder {
		rank[k] = i
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Kind != out[j].Kind {
			return rank[out[i].Kind] < rank[out[j].Kind]
		}
		return out[i].Name < out[j].Name
	})
	return out, nil
}

// TypeSuffix is the type name without the provider prefix ("docker_container"
// -> "container"); a function name is returned unchanged.
func TypeSuffix(t Type) string {
	if t.Kind == "function" {
		return t.Name
	}
	return strings.TrimPrefix(t.Name, "docker_")
}

// Constructor is the Go constructor name of t: "New" + CamelCase(suffix) +
// kind suffix, e.g. data docker_container_logs -> NewContainerLogsDataSource.
func Constructor(t Type) string {
	var b strings.Builder
	b.WriteString("New")
	for _, p := range strings.Split(TypeSuffix(t), "_") {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	b.WriteString(kinds[t.Kind].suffix)
	return b.String()
}

const header = "// Code generated by tools/registrygen from reference/inventory.json. DO NOT EDIT.\n// Regenerate: Invoke-Build RegistryGen (RegistryCheck fails when this file and the inventory differ).\n\n"

// Generate renders registry_gen.go and registry_gen_test.go for types.
func Generate(types []Type) (src, test []byte, err error) {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package provider\n\nimport (\n")
	for _, k := range kindOrder {
		fmt.Fprintf(&b, "\t%q\n", kinds[k].pkg)
	}
	b.WriteString(")\n")
	for _, k := range kindOrder {
		ki := kinds[k]
		fmt.Fprintf(&b, "\n// %s returns every %s constructor, one per %s name in the inventory.\n", ki.genFunc, strings.ReplaceAll(k, "_", " "), strings.ReplaceAll(k, "_", " "))
		fmt.Fprintf(&b, "func %s() []func() %s {\n\treturn []func() %s{\n", ki.genFunc, ki.iface, ki.iface)
		for _, t := range types {
			if t.Kind == k {
				// The trailing comment is read by reference/_gen/merge.py: "<kind> <name>".
				fmt.Fprintf(&b, "\t\t%s, // %s %s\n", Constructor(t), t.Kind, t.Name)
			}
		}
		b.WriteString("\t}\n}\n")
	}
	src, err = format.Source(b.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("formatting registry_gen.go: %w\n%s", err, b.String())
	}

	var tb bytes.Buffer
	tb.WriteString(header)
	tb.WriteString(`package provider

import (
	"context"
	"sort"
	"testing"

	"github.com/hashicorp/terraform-plugin-framework/action"
	"github.com/hashicorp/terraform-plugin-framework/datasource"
	"github.com/hashicorp/terraform-plugin-framework/ephemeral"
	"github.com/hashicorp/terraform-plugin-framework/function"
	"github.com/hashicorp/terraform-plugin-framework/resource"
)

// registryGenWant is every (kind, name) the inventory registers.
var registryGenWant = []string{
`)
	for _, t := range types {
		fmt.Fprintf(&tb, "\t%q,\n", t.Kind+" "+t.Name)
	}
	tb.WriteString(`}

// TestRegistryGen checks that every generated constructor reports the type
// name the inventory decided (its Metadata), and nothing else is registered.
func TestRegistryGen(t *testing.T) {
	ctx := context.Background()
	var got []string
	for _, f := range genResources() {
		var resp resource.MetadataResponse
		f().Metadata(ctx, resource.MetadataRequest{ProviderTypeName: "docker"}, &resp)
		got = append(got, "resource "+resp.TypeName)
	}
	for _, f := range genDataSources() {
		var resp datasource.MetadataResponse
		f().Metadata(ctx, datasource.MetadataRequest{ProviderTypeName: "docker"}, &resp)
		got = append(got, "data_source "+resp.TypeName)
	}
	for _, f := range genActions() {
		var resp action.MetadataResponse
		f().Metadata(ctx, action.MetadataRequest{ProviderTypeName: "docker"}, &resp)
		got = append(got, "action "+resp.TypeName)
	}
	for _, f := range genEphemeralResources() {
		var resp ephemeral.MetadataResponse
		f().Metadata(ctx, ephemeral.MetadataRequest{ProviderTypeName: "docker"}, &resp)
		got = append(got, "ephemeral_resource "+resp.TypeName)
	}
	for _, f := range genListResources() {
		var resp resource.MetadataResponse
		f().Metadata(ctx, resource.MetadataRequest{ProviderTypeName: "docker"}, &resp)
		got = append(got, "list_resource "+resp.TypeName)
	}
	for _, f := range genFunctions() {
		var resp function.MetadataResponse
		f().Metadata(ctx, function.MetadataRequest{}, &resp)
		got = append(got, "function "+resp.Name)
	}
	want := append([]string(nil), registryGenWant...)
	sort.Strings(got)
	sort.Strings(want)
	gi, wi := 0, 0
	for gi < len(got) || wi < len(want) {
		switch {
		case wi >= len(want) || (gi < len(got) && got[gi] < want[wi]):
			t.Errorf("registered but not in the inventory: %s", got[gi])
			gi++
		case gi >= len(got) || got[gi] > want[wi]:
			t.Errorf("in the inventory but no constructor reports it: %s", want[wi])
			wi++
		default:
			gi++
			wi++
		}
	}
}
`)
	test, err = format.Source(tb.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("formatting registry_gen_test.go: %w", err)
	}
	return src, test, nil
}
