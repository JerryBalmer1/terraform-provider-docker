package main

// Writing the covering array as Terraform root modules: one directory per
// row, <out>/<type>/<nn>/main.tf plus expect.json (what -compare checks).

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// expectFile is <config>/expect.json.
type expectFile struct {
	Type       string            `json:"type"`
	Config     string            `json:"config"`
	Address    string            `json:"address"`
	Endpoint   string            `json:"endpoint"`
	IDAttr     string            `json:"id_attr"`
	Contract   string            `json:"contract"`
	Assignment map[string]string `json:"assignment"`
	Checks     []expectCheck     `json:"checks"`
}

type expectCheck struct {
	Attr     string   `json:"attr"`
	Label    string   `json:"label"`
	Inspect  string   `json:"inspect"`
	Upstream []string `json:"upstream"`
	Match    string   `json:"match"`
	Expected any      `json:"expected"`
}

// shortType is the type name without the docker_ prefix, for config names.
func shortType(t string) string { return strings.TrimPrefix(t, "docker_") }

func configName(t string, i int) string { return fmt.Sprintf("pw-%s-%02d", shortType(t), i+1) }

// writeConfigs replaces <out>/<type> with one directory per row.
func writeConfigs(out string, cm *compiledModel, rows [][]int) error {
	base := filepath.Join(out, cm.Model.Type)
	if err := os.RemoveAll(base); err != nil {
		return err
	}
	for i, row := range rows {
		name := configName(cm.Model.Type, i)
		dir := filepath.Join(base, fmt.Sprintf("%02d", i+1))
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		tf, err := renderConfig(cm, row, name, i, len(rows))
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, "main.tf"), tf, 0o644); err != nil {
			return err
		}
		if err := writeJSON(filepath.Join(dir, "expect.json"), buildExpect(cm, row, name)); err != nil {
			return err
		}
	}
	type arrayRow struct {
		Config     string            `json:"config"`
		Assignment map[string]string `json:"assignment"`
	}
	var arr []arrayRow
	for i, row := range rows {
		arr = append(arr, arrayRow{Config: configName(cm.Model.Type, i), Assignment: cm.labelMap(row)})
	}
	return writeJSON(filepath.Join(base, "array.json"), arr)
}

func buildExpect(cm *compiledModel, row []int, name string) expectFile {
	e := expectFile{
		Type:       cm.Model.Type,
		Config:     name,
		Address:    cm.Model.Type + ".pw",
		Endpoint:   cm.Model.Inspect.Endpoint,
		IDAttr:     cm.Model.Inspect.IDAttr,
		Contract:   cm.Upstream,
		Assignment: cm.labelMap(row),
		Checks:     []expectCheck{},
	}
	for fi, vi := range row {
		f := cm.Factors[fi]
		v := f.Values[vi]
		if f.Match == "none" || !v.HasExpect {
			continue
		}
		e.Checks = append(e.Checks, expectCheck{Attr: f.Path, Label: v.Label, Inspect: f.Inspect, Upstream: f.Upstream, Match: f.Match, Expected: v.Expect})
	}
	return e
}

func writeJSON(path string, v any) error {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(b, '\n'), 0o644)
}

// renderConfig renders one row as a standalone root module.
func renderConfig(cm *compiledModel, row []int, name string, i, total int) ([]byte, error) {
	// Merge fixed values and the row's values into one tree.
	tree := map[string]any{}
	for _, p := range sortedKeys(cm.Fixed) {
		if err := place(cm.Schema, tree, p, cm.Fixed[p]); err != nil {
			return nil, err
		}
	}
	for fi, vi := range row {
		f := cm.Factors[fi]
		if v := f.Values[vi].Set; v != nil {
			if err := place(cm.Schema, tree, f.Path, v); err != nil {
				return nil, err
			}
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by tools/pairwise from reference/_gen/pairwise/%s.json; do not edit.\n", cm.Model.Type)
	fmt.Fprintf(&b, "# Config %d of %d. Values:\n", i+1, total)
	for _, kv := range cm.labels(row) {
		fmt.Fprintf(&b, "#   %s = %s\n", kv[0], kv[1])
	}
	b.WriteString(`
terraform {
  required_providers {
    docker = {
      source = "JerryBalmer1/docker"
    }
  }
}

# The Engine endpoint comes from DOCKER_HOST.
provider "docker" {}

# Registry prefix for the harness copies of Docker Hub images ("manager:12380/"), empty for Docker Hub.
variable "pw_registry" {
  type    = string
  default = ""
}

`)
	fmt.Fprintf(&b, "locals {\n  prefix = %s\n}\n\n", hclString(name))
	if strings.TrimSpace(cm.Model.Prelude) != "" {
		b.WriteString(strings.TrimRight(cm.Model.Prelude, "\n"))
		b.WriteString("\n\n")
	}
	fmt.Fprintf(&b, "resource %s \"pw\" {\n", hclString(cm.Model.Type))
	if err := renderBody(&b, cm.Schema.Children, tree, 1); err != nil {
		return nil, err
	}
	b.WriteString("}\n")
	return []byte(b.String()), nil
}

// place puts v at the dotted path p of tree, creating single objects (and
// the first element of list blocks) on the way.
func place(s *resourceSchema, tree map[string]any, p string, v any) error {
	chain, err := s.lookup(p)
	if err != nil {
		return err
	}
	segs := strings.Split(p, ".")
	cur := tree
	for i, seg := range segs[:len(segs)-1] {
		n := chain[i]
		switch n.Nesting {
		case nestSingle:
			next, ok := cur[seg].(map[string]any)
			if !ok {
				next = map[string]any{}
				cur[seg] = next
			}
			cur = next
		default: // list/set: first element
			l, _ := cur[seg].([]any)
			if len(l) == 0 {
				l = []any{map[string]any{}}
				cur[seg] = l
			}
			next, ok := l[0].(map[string]any)
			if !ok {
				return fmt.Errorf("%s: cannot place %s below a non-object", p, seg)
			}
			cur = next
		}
	}
	cur[segs[len(segs)-1]] = v
	return nil
}

func indent(n int) string { return strings.Repeat("  ", n) }

// renderBody writes the attributes (name = value) and then the blocks of an object.
func renderBody(b *strings.Builder, schema map[string]*schemaNode, obj map[string]any, depth int) error {
	keys := sortedKeys(obj)
	width := 0
	for _, k := range keys {
		if n := schema[k]; n != nil && n.Kind != kindBlock && len(k) > width {
			width = len(k)
		}
	}
	for _, k := range keys {
		n := schema[k]
		if n == nil {
			return fmt.Errorf("unknown attribute %q", k)
		}
		if n.Kind == kindBlock || obj[k] == nil {
			continue
		}
		fmt.Fprintf(b, "%s%-*s = ", indent(depth), width, k)
		if err := renderValue(b, n, obj[k], depth); err != nil {
			return fmt.Errorf("%s: %w", k, err)
		}
		b.WriteString("\n")
	}
	wrote := b.Len()
	for _, k := range keys {
		n := schema[k]
		if n.Kind != kindBlock || obj[k] == nil {
			continue
		}
		var elems []any
		switch n.Nesting {
		case nestSingle:
			elems = []any{obj[k]}
		case nestMap:
			return fmt.Errorf("%s: map blocks are not supported", k)
		default:
			l, ok := obj[k].([]any)
			if !ok {
				return fmt.Errorf("%s: want a list of blocks", k)
			}
			elems = l
		}
		for _, e := range elems {
			m, ok := e.(map[string]any)
			if !ok {
				return fmt.Errorf("%s: block is not an object", k)
			}
			if s := b.String(); b.Len() != wrote || !strings.HasSuffix(s, "{\n") {
				b.WriteString("\n")
			}
			fmt.Fprintf(b, "%s%s {\n", indent(depth), k)
			if err := renderBody(b, n.Children, m, depth+1); err != nil {
				return fmt.Errorf("%s: %w", k, err)
			}
			fmt.Fprintf(b, "%s}\n", indent(depth))
		}
	}
	return nil
}

// renderValue writes an attribute value; nested attributes render their
// objects with schema knowledge, plain values as HCL literals.
func renderValue(b *strings.Builder, n *schemaNode, v any, depth int) error {
	if h, ok := v.(hclExpr); ok {
		b.WriteString(string(h))
		return nil
	}
	if n.Kind == kindAttr {
		b.WriteString(hclLiteral(v, depth))
		return nil
	}
	obj := func(x any, d int) error {
		m, ok := x.(map[string]any)
		if !ok {
			if h, ok := x.(hclExpr); ok {
				b.WriteString(string(h))
				return nil
			}
			return fmt.Errorf("want an object")
		}
		b.WriteString("{\n")
		if err := renderBody(b, n.Children, m, d+1); err != nil {
			return err
		}
		b.WriteString(indent(d) + "}")
		return nil
	}
	switch n.Nesting {
	case nestSingle:
		return obj(v, depth)
	case nestMap:
		m, ok := v.(map[string]any)
		if !ok {
			return fmt.Errorf("want a map")
		}
		b.WriteString("{\n")
		for _, k := range sortedKeys(m) {
			fmt.Fprintf(b, "%s%s = ", indent(depth+1), hclString(k))
			if err := obj(m[k], depth+1); err != nil {
				return err
			}
			b.WriteString("\n")
		}
		b.WriteString(indent(depth) + "}")
		return nil
	default:
		l, ok := v.([]any)
		if !ok {
			return fmt.Errorf("want a list")
		}
		if len(l) == 0 {
			b.WriteString("[]")
			return nil
		}
		b.WriteString("[\n")
		for _, e := range l {
			b.WriteString(indent(depth + 1))
			if err := obj(e, depth+1); err != nil {
				return err
			}
			b.WriteString(",\n")
		}
		b.WriteString(indent(depth) + "]")
		return nil
	}
}

// hclLiteral renders decoded JSON as an HCL literal.
func hclLiteral(v any, depth int) string {
	switch t := v.(type) {
	case nil:
		return "null"
	case hclExpr:
		return string(t)
	case bool:
		return strconv.FormatBool(t)
	case float64:
		return strconv.FormatFloat(t, 'f', -1, 64)
	case string:
		return hclString(t)
	case []any:
		parts := make([]string, len(t))
		for i, e := range t {
			parts[i] = hclLiteral(e, depth+1)
		}
		return "[" + strings.Join(parts, ", ") + "]"
	case map[string]any:
		if len(t) == 0 {
			return "{}"
		}
		keys := make([]string, 0, len(t))
		for k := range t {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		var b strings.Builder
		b.WriteString("{\n")
		for _, k := range keys {
			fmt.Fprintf(&b, "%s%s = %s\n", indent(depth+1), hclString(k), hclLiteral(t[k], depth+1))
		}
		b.WriteString(indent(depth) + "}")
		return b.String()
	}
	return fmt.Sprintf("%v", v)
}

// hclString quotes s as an HCL string literal (template sequences escaped).
func hclString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		case '$', '%':
			if i+1 < len(s) && s[i+1] == '{' {
				b.WriteByte(c)
			}
			b.WriteByte(c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}
