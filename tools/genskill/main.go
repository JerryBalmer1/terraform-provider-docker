// generatedMarker identifies files this tool owns. Stale reference files are
// removed only when they carry it.
const generatedMarker = "<!-- Code generated by tools/genskill from the provider schema. DO NOT EDIT. -->"

const (
	kindResource   = "resource"
	kindDataSource = "data-source"
	kindProvider   = "provider"
)

//go:embed templates/*.tmpl
var templateFS embed.FS

func main() {
	var o options
	flag.StringVar(&o.Out, "out", filepath.Join("skills", "terraform-provider-docker"), "output directory of the skill")
	flag.StringVar(&o.Examples, "examples", "examples", "examples directory (examples/resources/<type>/resource.tf, import.sh, examples/data-sources/<type>/data-source.tf)")
	flag.StringVar(&o.Readme, "readme", "README_resources.md", "path of the generated resource index; empty disables it")
	flag.StringVar(&o.Docs, "docs", "docs", "tfplugindocs output directory the resource index links to")
	flag.BoolVar(&o.Check, "check", false, "render in memory and exit non-zero if files on disk differ")
	flag.BoolVar(&o.Strict, "strict", false, "exit non-zero if an attribute or block with a RequiresReplace plan modifier has no replacement sentence in its description (does not write files)")
	flag.Parse()
	if err := run(context.Background(), o, os.Stdout, os.Stderr); err != nil {
		fmt.Fprintln(os.Stderr, "genskill:", err)
		os.Exit(1)
	}
}

type options struct {
	Out      string
	Examples string
	Readme   string
	Docs     string
	Check    bool
	Strict   bool
}

var (
	errDrift  = errors.New("skill is out of date; run `go run ./tools/genskill`")
	errStrict = errors.New(`RequiresReplace attributes without a replacement sentence (add "Forces replacement." to their MarkdownDescription)`)
)

func run(ctx context.Context, o options, stdout, stderr io.Writer) error {
	resp, err := loadSchema(ctx)
	if err != nil {
		return err
	}
	fw, err := frameworkResources(ctx, provider.New("dev")())
	if err != nil {
		return err
	}
	repl, violations := frameworkReplacements(fw)

	var errs []error
	if o.Strict {
		for _, v := range violations {
			fmt.Fprintln(stderr, "genskill: strict:", v)
		}
		if len(violations) > 0 {
			fmt.Fprintf(stderr, "genskill: strict: %d violation(s)\n", len(violations))
			errs = append(errs, errStrict)
		} else {
			fmt.Fprintf(stdout, "genskill: strict: every RequiresReplace attribute says it forces replacement (%d resources)\n", len(fw))
		}
		if !o.Check {
			return errors.Join(errs...)
		}
	}

	ro := renderOpts{Examples: o.Examples, Replace: repl}
	if o.Readme != "" {
		ro.ReadmeSkillDir = relLink(o.Readme, o.Out)
		ro.ReadmeDocsDir = relLink(o.Readme, o.Docs)
	}
	files, readme, warnings, err := render(resp, ro)
	if err != nil {
		return err
	}
	for _, w := range warnings {
		fmt.Fprintln(stderr, "genskill: warning:", w)
	}
	if o.Check {
		diffs, err := checkFiles(o.Out, files)
		if err != nil {
			return err
		}
		if o.Readme != "" {
			d, err := checkFile(o.Readme, readme)
			if err != nil {
				return err
			}
			if d != "" {
				diffs = append(diffs, d)
			}
		}
		for _, d := range diffs {
			fmt.Fprintln(stderr, "genskill: drift:", d)
		}
		if len(diffs) > 0 {
			errs = append(errs, errDrift)
		} else {
			fmt.Fprintf(stdout, "genskill: %s is up to date (%d files)\n", o.Out, len(files))
			if o.Readme != "" {
				fmt.Fprintf(stdout, "genskill: %s is up to date\n", o.Readme)
			}
		}
		return errors.Join(errs...)
	}
	removed, err := writeFiles(o.Out, files)
	if err != nil {
		return err
	}
	for _, r := range removed {
		fmt.Fprintln(stdout, "genskill: removed stale", r)
	}
	fmt.Fprintf(stdout, "genskill: wrote %d files to %s\n", len(files), o.Out)
	if o.Readme != "" {
		if err := os.WriteFile(o.Readme, readme, 0o644); err != nil {
			return err
		}
		fmt.Fprintf(stdout, "genskill: wrote %s\n", o.Readme)
	}
	return nil
}

// relLink returns target relative to the directory of file, slash separated,
// for markdown links written into file.
func relLink(file, target string) string {
	fa, err1 := filepath.Abs(filepath.Dir(file))
	ta, err2 := filepath.Abs(target)
	if err1 == nil && err2 == nil {
		if rel, err := filepath.Rel(fa, ta); err == nil {
			return filepath.ToSlash(rel)
		}
	}
	return filepath.ToSlash(target)
}

// loadSchema serves the provider in-process and returns its protocol schema.
func loadSchema(ctx context.Context) (*tfprotov6.GetProviderSchemaResponse, error) {
	srv, err := providerserver.NewProtocol6WithError(provider.New("dev")())()
	if err != nil {
		return nil, fmt.Errorf("serving provider: %w", err)
	}
	resp, err := srv.GetProviderSchema(ctx, &tfprotov6.GetProviderSchemaRequest{})
	if err != nil {
		return nil, fmt.Errorf("GetProviderSchema: %w", err)
	}
	var msgs []string
	for _, d := range resp.Diagnostics {
		if d.Severity == tfprotov6.DiagnosticSeverityError {
			msgs = append(msgs, d.Summary+": "+d.Detail)
		}
	}
	if len(msgs) > 0 {
		return nil, fmt.Errorf("GetProviderSchema diagnostics: %s", strings.Join(msgs, "; "))
	}
	return resp, nil
}

// ===== schema model =====

type attrInfo struct {
	Name              string
	Path              string // dotted path from the type root, e.g. build.context
	Type              string
	Required          bool
	Optional          bool
	Computed          bool
	Sensitive         bool
	ForcesReplacement bool
	Deprecated        bool
	Description       string
	Nested            *blockInfo // nested attribute object, if any
}

type blockInfo struct {
	Name        string
	Path        string
	Nesting     string
	MinItems    int64
	MaxItems    int64
	Description string
	// ForcesReplacement: the block carries a RequiresReplace plan modifier
	// or its description says it forces replacement.
	ForcesReplacement bool
	Attributes        []attrInfo
	Blocks            []blockInfo
}

type typeDoc struct {
	Name        string
	Kind        string
	Description string
	Root        blockInfo
	Example     string
	Import      string
}

// Address is how HCL refers to the type: docker_x or data.docker_x.
func (t typeDoc) Address() string {
	if t.Kind == kindDataSource {
		return "data." + t.Name
	}
	return t.Name
}

// File is the reference file name relative to the skill directory.
func (t typeDoc) File() string {
	switch t.Kind {
	case kindDataSource:
		return "reference/data." + t.Name + ".md"
	case kindProvider:
		return "reference/provider.md"
	}
	return "reference/" + t.Name + ".md"
}

// DocPage is the tfplugindocs page relative to the docs directory.
func (t typeDoc) DocPage() string {
	short := strings.TrimPrefix(t.Name, "docker_")
	switch t.Kind {
	case kindDataSource:
		return "data-sources/" + short + ".md"
	case kindProvider:
		return "index.md"
	}
	return "resources/" + short + ".md"
}

// forcesReplacement reports whether a description states that changing the
// value forces replacement ("Forces replacement." or "Changing this forces a
// new resource."). It is the fallback signal where no framework plan modifier
// is visible, and the sentence -strict requires on RequiresReplace attributes.
func forcesReplacement(desc string) bool {
	d := strings.ToLower(desc)
	for _, p := range []string{"forces a new ", "force a new ", "forces replacement", "forces a replacement"} {
		if strings.Contains(d, p) {
			return true
		}
	}
	return false
}

func typeString(t tftypes.Type) string {
	if t == nil {
		return ""
	}
	switch v := t.(type) {
	case tftypes.List:
		return "list(" + typeString(v.ElementType) + ")"
	case tftypes.Set:
		return "set(" + typeString(v.ElementType) + ")"
	case tftypes.Map:
		return "map(" + typeString(v.ElementType) + ")"
	case tftypes.Tuple:
		return "tuple"
	case tftypes.Object:
		names := make([]string, 0, len(v.AttributeTypes))
		for n := range v.AttributeTypes {
			names = append(names, n)
		}
		sort.Strings(names)
		parts := make([]string, len(names))
		for i, n := range names {
			parts[i] = n + "=" + typeString(v.AttributeTypes[n])
		}
		return "object({" + strings.Join(parts, ", ") + "})"
	}
	switch {
	case t.Is(tftypes.String):
		return "string"
	case t.Is(tftypes.Number):
		return "number"
	case t.Is(tftypes.Bool):
		return "bool"
	case t.Is(tftypes.DynamicPseudoType):
		return "dynamic"
	}
	return t.String()
}

func blockNesting(m tfprotov6.SchemaNestedBlockNestingMode) string {
	switch m {
	case tfprotov6.SchemaNestedBlockNestingModeSingle:
		return "single block"
	case tfprotov6.SchemaNestedBlockNestingModeList:
		return "list of blocks"
	case tfprotov6.SchemaNestedBlockNestingModeSet:
		return "set of blocks"
	case tfprotov6.SchemaNestedBlockNestingModeMap:
		return "map of blocks"
	case tfprotov6.SchemaNestedBlockNestingModeGroup:
		return "group block"
	}
	return "block"
}

func objectNesting(m tfprotov6.SchemaObjectNestingMode) string {
	switch m {
	case tfprotov6.SchemaObjectNestingModeSingle:
		return "object"
	case tfprotov6.SchemaObjectNestingModeList:
		return "list(object)"
	case tfprotov6.SchemaObjectNestingModeSet:
		return "set(object)"
	case tfprotov6.SchemaObjectNestingModeMap:
		return "map(object)"
	}
	return "object"
}

func joinPath(prefix, name string) string {
	if prefix == "" {
		return name
	}
	return prefix + "." + name
}

func walkAttributes(prefix string, attrs []*tfprotov6.SchemaAttribute) []attrInfo {
	out := make([]attrInfo, 0, len(attrs))
	for _, a := range attrs {
		if a == nil {
			continue
		}
		p := joinPath(prefix, a.Name)
		ai := attrInfo{
			Name:              a.Name,
			Path:              p,
			Type:              typeString(a.Type),
			Required:          a.Required,
			Optional:          a.Optional,
			Computed:          a.Computed,
			Sensitive:         a.Sensitive,
			Deprecated:        a.Deprecated,
			Description:       strings.TrimSpace(a.Description),
			ForcesReplacement: forcesReplacement(a.Description),
		}
		if a.NestedType != nil {
			ai.Type = objectNesting(a.NestedType.Nesting)
			ai.Nested = &blockInfo{
				Name:        a.Name,
				Path:        p,
				Nesting:     "nested attribute, " + ai.Type,
				Description: ai.Description,
				Attributes:  walkAttributes(p, a.NestedType.Attributes),
			}
		}
		out = append(out, ai)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

func walkBlock(name, path, nesting string, b *tfprotov6.SchemaBlock) blockInfo {
	bi := blockInfo{Name: name, Path: path, Nesting: nesting}
	if b == nil {
		return bi
	}
	bi.Description = strings.TrimSpace(b.Description)
	bi.ForcesReplacement = path != "" && forcesReplacement(b.Description)
	bi.Attributes = walkAttributes(path, b.Attributes)
	for _, nb := range b.BlockTypes {
		if nb == nil {
			continue
		}
		child := walkBlock(nb.TypeName, joinPath(path, nb.TypeName), blockNesting(nb.Nesting), nb.Block)
		child.MinItems, child.MaxItems = nb.MinItems, nb.MaxItems
		bi.Blocks = append(bi.Blocks, child)
	}
	sort.Slice(bi.Blocks, func(i, j int) bool { return bi.Blocks[i].Name < bi.Blocks[j].Name })
	return bi
}

func walkSchema(name, kind string, s *tfprotov6.Schema) typeDoc {
	td := typeDoc{Name: name, Kind: kind}
	if s == nil {
		return td
	}
	td.Root = walkBlock(name, "", "", s.Block)
	td.Description = td.Root.Description
	return td
}

// subBlocks flattens every nested block and nested-attribute object under b
// in document order (depth first).
func subBlocks(b blockInfo) []blockInfo {
	var out []blockInfo
	for _, a := range b.Attributes {
		if a.Nested != nil {
			out = append(out, *a.Nested)
			out = append(out, subBlocks(*a.Nested)...)
		}
	}
	for _, c := range b.Blocks {
		out = append(out, c)
		out = append(out, subBlocks(c)...)
	}
	return out
}

// markReplacements sets ForcesReplacement on every attribute and block of b
// whose path the framework walk flagged as RequiresReplace. The description
// text flag set by the protocol walk stays as the fallback.
func markReplacements(b *blockInfo, typeName string, set replaceSet) {
	if set == nil {
		return
	}
	for i := range b.Attributes {
		a := &b.Attributes[i]
		if set.has(typeName, a.Path) {
			a.ForcesReplacement = true
		}
		if a.Nested != nil {
			markReplacements(a.Nested, typeName, set)
		}
	}
	for i := range b.Blocks {
		c := &b.Blocks[i]
		if set.has(typeName, c.Path) {
			c.ForcesReplacement = true
		}
		markReplacements(c, typeName, set)
	}
}

// replNode is an attribute or block that forces replacement.
type replNode struct {
	Path        string
	Description string
	Block       bool
}

// replacementAttrs lists every attribute and block under b that forces
// replacement, in document order.
func replacementAttrs(b blockInfo) []replNode {
	var out []replNode
	for _, a := range b.Attributes {
		if a.ForcesReplacement {
			out = append(out, replNode{Path: a.Path, Description: a.Description})
		}
		if a.Nested != nil {
			out = append(out, replacementAttrs(*a.Nested)...)
		}
	}
	for _, c := range b.Blocks {
		if c.ForcesReplacement {
			out = append(out, replNode{Path: c.Path, Description: c.Description, Block: true})
		}
		out = append(out, replacementAttrs(c)...)
	}
	return out
}

// hasPath reports whether a dotted attribute or block path exists under b.
func hasPath(b blockInfo, path string) bool {
	head, rest, more := strings.Cut(path, ".")
	for _, a := range b.Attributes {
		if a.Name == head {
			if !more {
				return true
			}
			return a.Nested != nil && hasPath(*a.Nested, rest)
		}
	}
	for _, c := range b.Blocks {
		if c.Name == head {
			if !more {
				return true
			}
			return hasPath(c, rest)
		}
	}
	return false
}

