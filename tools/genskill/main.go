// All returns every type of the layer in table order.
func (l layerView) All() []typeDoc {
	var out []typeDoc
	for _, s := range [][]typeDoc{l.Resources, l.DataSources, l.Actions, l.Ephemeral, l.Lists, l.Functions} {
		out = append(out, s...)
	}
	return out
}

